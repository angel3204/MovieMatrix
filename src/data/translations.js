export function t(key, lang = "en", vars = {}) {
    const selectedLang = lang === "hi" ? "hi" : "en";
    let text = (translations[selectedLang] && translations[selectedLang][key]) 
        || (translations["en"] && translations["en"][key]) 
        || key;
    if (vars && typeof vars === "object") {
        for (const [varName, varVal] of Object.entries(vars)) {
            text = text.replace(new RegExp(`\\{${varName}\\}`, "g"), varVal);
        }
    }
    return text;
}
