function getLanguage() {
    try {
        const saved = localStorage.getItem(MOVIE_MATRIX_LANG_KEY);
        if (saved === "hi" || saved === "en") return saved;
    } catch (e) {
        console.error("Movie Matrix i18n: Failed to read language from localStorage", e);
    }
    return "en";
}

function t(key, vars = {}, langOverride = null) {
    const lang = langOverride || getLanguage();
    let text = (translations[lang] && translations[lang][key]) || (translations["en"] && translations["en"][key]) || key;
    if (vars && typeof vars === "object") {
        for (const [varName, varVal] of Object.entries(vars)) {
            text = text.replace(new RegExp(`\\{${varName}\\}`, "g"), varVal);
        }
    }
    return text;
}

function applyLanguageToDOM(lang = getLanguage()) {
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (!key) return;
        const translated = t(key, {}, lang);
        if (translated) {
            el.textContent = translated;
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (!key) return;
        const translated = t(key, {}, lang);
        if (translated) {
            el.placeholder = translated;
        }
    });

    document.querySelectorAll("[data-i18n-title]").forEach(el => {
        const key = el.getAttribute("data-i18n-title");
        if (!key) return;
        const translated = t(key, {}, lang);
        if (translated) {
            el.title = translated;
        }
    });

    document.querySelectorAll("#navbar-lang-select, .lang-select").forEach(sel => {
        sel.value = lang;
    });

    const searchInput = document.getElementById("search-input");
    if (searchInput) {
        if (typeof currentTab !== "undefined") {
            if (currentTab === "movies") searchInput.placeholder = t("searchPlaceholderMovies", {}, lang);
            else if (currentTab === "tv") searchInput.placeholder = t("searchPlaceholderTv", {}, lang);
            else searchInput.placeholder = t("searchPlaceholder", {}, lang);
        } else {
            searchInput.placeholder = t("searchPlaceholder", {}, lang);
        }
    }
}

function setLanguage(lang, showNotification = true) {
    if (lang !== "en" && lang !== "hi") lang = "en";

    try {
        localStorage.setItem(MOVIE_MATRIX_LANG_KEY, lang);
    } catch (e) {
        console.error("Movie Matrix i18n: Failed to save language to localStorage", e);
    }

    if (document.body) {
        document.body.classList.add("lang-transitioning");
        setTimeout(() => {
            if (document.body) document.body.classList.remove("lang-transitioning");
        }, 200);
    }

    applyLanguageToDOM(lang);

    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));

    if (showNotification && typeof showToast === "function") {
        showToast(t("languageChangedMsg"), "info");
    }
}

function initLanguageSystem() {
    let activeLang = getLanguage();
    try {
        if (!localStorage.getItem(MOVIE_MATRIX_LANG_KEY)) {
            activeLang = "en";
            localStorage.setItem(MOVIE_MATRIX_LANG_KEY, "en");
        }
    } catch (e) {}
    applyLanguageToDOM(activeLang);

    document.querySelectorAll("#navbar-lang-select, .lang-select").forEach(sel => {
        sel.value = activeLang;
        sel.addEventListener("change", (e) => {
            setLanguage(e.target.value, true);
        });
    });

    window.addEventListener("languageChanged", (e) => {
        if (typeof loadTab === "function" && typeof currentTab !== "undefined") {
            loadTab(currentTab);
        } else if (typeof renderRows === "function") {
            renderRows();
        }
        if (typeof updateAllCardRatings === "function") {
            updateAllCardRatings();
        }
    });
}

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initLanguageSystem);
} else {
    initLanguageSystem();
}

window.getLanguage = getLanguage;
window.setLanguage = setLanguage;
window.t = t;
window.applyLanguageToDOM = applyLanguageToDOM;
window.initLanguageSystem = initLanguageSystem;

